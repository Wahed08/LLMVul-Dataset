# Mining Loop
def mine():
    if not GITHUB_TOKEN:
        raise ValueError(
            "Set GITHUB_TOKEN environment variable"
        )

    g = Github(GITHUB_TOKEN, per_page=100)
    init_csv()

    stats = {
        "repos_scanned":   0,
        "commits_scanned": 0,
        "llm_commits":     0,
        "functions_saved": 0,
        "by_tool":         {},
        "by_language":     {"c": 0, "cpp": 0},
        "by_strength":     {
            "strong": 0, "medium": 0
        },
    }

    seen_repos   = set()
    search_queries = [
        f"language:C stars:>200 "
        f"pushed:>{START_DATE}",
        f"language:C++ stars:>200 "
        f"pushed:>{START_DATE}",
    ]

    log.info("LLMVul Mining Started")
    log.info(
        f"Target: {MAX_REPOS} repos | "
        f"{MAX_COMMITS} commits each"
    )

    for query in search_queries:
        if stats["repos_scanned"] >= MAX_REPOS:
            break

        log.info(f"Query: {query}")
        repos = g.search_repositories(
            query=query,
            sort="stars",
            order="desc"
        )

        for repo in repos:
            if stats["repos_scanned"] >= MAX_REPOS:
                break
            if repo.full_name in seen_repos:
                continue
            seen_repos.add(repo.full_name)

            log.info(
                f"[{stats['repos_scanned']+1}/"
                f"{MAX_REPOS}] {repo.full_name} "
                f"⭐{repo.stargazers_count}"
            )

            repo_count   = 0
            commit_count = 0

            try:
                for commit in repo.get_commits():
                    if commit_count >= MAX_COMMITS:
                        break

                    try:
                        msg = commit.commit.message
                        commit_count += 1
                        stats["commits_scanned"] += 1

                        is_llm, tool, strength, \
                            sig_type = \
                            detect_attribution(msg)

                        if not is_llm:
                            time.sleep(0.02)
                            continue

                        stats["llm_commits"] += 1
                        stats["by_tool"][tool] = \
                            stats["by_tool"].get(
                                tool, 0
                            ) + 1
                        stats["by_strength"][
                            strength
                        ] += 1

                        log.info(
                            f"  ✓ [{tool}|{strength}]"
                            f" {commit.sha[:8]}"
                        )

                        for file in commit.files:
                            ext = Path(
                                file.filename
                            ).suffix.lower()
                            if ext not in \
                               TARGET_EXTENSIONS:
                                continue
                            if not file.patch:
                                continue

                            lang = \
                                TARGET_EXTENSIONS[ext]
                            added = get_added_code(
                                file.patch
                            )

                            if len(added.strip()) < 50:
                                continue

                            functions = \
                                extract_functions(
                                    added, lang
                                )

                            try:
                                content = \
                                    repo.get_contents(
                                        file.filename,
                                        ref=commit.sha
                                    ).decoded_content\
                                     .decode(
                                         "utf-8",
                                         errors="replace"
                                     )
                                fhash = \
                                    compute_file_hash(
                                        content
                                    )
                            except Exception:
                                fhash = \
                                    compute_file_hash(
                                        added
                                    )

                            for func in functions:
                                uid = make_unique_id(
                                    repo.full_name,
                                    commit.sha,
                                    file.filename,
                                    func[
                                      "function_start"
                                      "_line"
                                    ]
                                )
                                record = {
                                    "unique_id":
                                        uid,
                                    "project_name":
                                        repo.full_name,
                                    "project_url":
                                        repo.html_url,
                                    "commit_id":
                                        commit.sha,
                                    "commit_url":
                                        f"{repo.html_url}"
                                        f"/commit/"
                                        f"{commit.sha}",
                                    "commit_message":
                                        msg[:1000],
                                    "commit_date":
                                        commit.commit
                                        .author.date
                                        .isoformat(),
                                    "file_name":
                                        file.filename,
                                    "file_hash":
                                        fhash,
                                    "language":
                                        lang,
                                    "function_body":
                                        func[
                                          "function"
                                          "_body"
                                        ],
                                    "function_start"
                                    "_line":
                                        func[
                                          "function"
                                          "_start_line"
                                        ],
                                    "function_end"
                                    "_line":
                                        func[
                                          "function"
                                          "_end_line"
                                        ],
                                    "function_lines":
                                        func[
                                          "function"
                                          "_lines"
                                        ],
                                    "ai_tool":
                                        tool,
                                    "signal_strength":
                                        strength,
                                    "signal_type":
                                        sig_type,
                                    "repo_stars":
                                        repo
                                        .stargazers_count,
                                    "repo_forks":
                                        repo.forks_count,
                                    "repo_primary"
                                    "_language":
                                        repo.language,
                                    "mined_at":
                                        datetime
                                        .utcnow()
                                        .isoformat(),
                                }
                                append_record(record)
                                repo_count   += 1
                                stats[
                                  "functions_saved"
                                ] += 1
                                stats[
                                  "by_language"
                                ][lang] += 1

                        time.sleep(0.05)

                    except RateLimitExceededException:
                        reset = g.get_rate_limit()\
                                 .core.reset
                        wait  = max(
                            0,
                            int((
                                reset.replace(
                                    tzinfo=None
                                ) - datetime.utcnow()
                            ).total_seconds()) + 10
                        )
                        log.warning(
                            f"Rate limit — "
                            f"sleeping {wait}s"
                        )
                        time.sleep(wait)

                    except Exception as e:
                        log.debug(f"Commit error: {e}")
                        continue

                log.info(
                    f"  → {repo_count} functions saved"
                )

            except Exception as e:
                log.error(f"Repo error: {e}")

            stats["repos_scanned"] += 1

    # Final summary
    log.info("=" * 50)
    log.info("Mining Complete")
    log.info(
        f"Repos scanned:    "
        f"{stats['repos_scanned']:,}"
    )
    log.info(
        f"Commits scanned:  "
        f"{stats['commits_scanned']:,}"
    )
    log.info(
        f"LLM commits:      "
        f"{stats['llm_commits']:,}"
    )
    log.info(
        f"Functions saved:  "
        f"{stats['functions_saved']:,}"
    )
    log.info(f"By tool:    {stats['by_tool']}")
    log.info(f"By language:{stats['by_language']}")
    log.info("=" * 50)


