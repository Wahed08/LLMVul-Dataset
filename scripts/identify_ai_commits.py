#!/usr/bin/env python3
"""Step 02 - Identify AI-attributed commits with rule-based signals.

Strong signals: tool metadata injected in Git (Co-authored-by trailers, etc.).
Medium signals: developer self-declaration in the commit message.


Usage:
    python scripts/identify_ai_commits.py [--selftest]
"""
import argparse
import json
import re
from collections import Counter

from common import AI_COMMITS, RAW_COMMITS

STRONG_PATTERNS = {
    "copilot": [
        r"co-authored-by:.*github[\s_]?copilot",
        r"co-authored-by:.*copilot",
        r"co-authored-by:.*copilot-noreply",
    ],
    "cursor": [
        r"co-authored-by:.*cursor",
        r"co-authored-by:.*anysphere",
        r"co-authored-by:.*cursor-noreply",
    ],
    "claude_code": [
        r"co-authored-by:.*claude",
        r"co-authored-by:.*anthropic",
        r"generated with \[claude code\]",
        r"co-authored-by:.*claude-code",
    ],
    "openai_codex": [
        r"co-authored-by:.*codex",
        r"co-authored-by:.*openai",
    ],
    "devin": [
        r"co-authored-by:.*devin",
        r"co-authored-by:.*cognition",
    ],
    "chatgpt": [
        r"co-authored-by:.*chatgpt",
        r"co-authored-by:.*gpt",
    ],
    "gemini": [
        r"co-authored-by:.*gemini",
        r"co-authored-by:.*google",
    ],
}

MEDIUM_PATTERNS = {
    "copilot": [
        r"copilot[\s\-]*(generated|suggested|wrote|assisted|helped|pair)",
        r"generated (by|with|using) (github )?copilot",
        r"(via|using|with) (?:github )?copilot",
        r"github copilot",
        r"\bcopilot\b",
    ],
    "chatgpt": [
        r"(chatgpt|chat gpt|gpt[\s\-]?[34o]|gpt[\s\-]?4o)",
        r"generated (by|with|using) (chat)?gpt",
        r"openai[\s\-]*(generated|helped|assisted|wrote)",
    ],
    "claude": [
        r"claude[\s\-]*(generated|wrote|suggested|helped|assisted|code)",
        r"generated (by|with|using) claude",
        r"(via|using|with) claude",
        r"anthropic[\s\-]*(generated|helped|wrote)",
    ],
    "cursor": [
        r"cursor[\s\-]*(generated|wrote|ai|assisted|helped)",
        r"(via|using|with) cursor[\s\-]*(ai|ide)?",
        r"\bcursor\s+ai\b",
    ],
    "gemini": [
        r"gemini[\s\-]*(generated|wrote|suggested|helped|assisted)",
        r"generated (by|with|using) gemini",
        r"google[\s\-]*gemini",
    ],
    "generic_llm": [
        r"\bai[\s\-]generated\b",
        r"\bllm[\s\-]generated\b",
        r"\bai[\s\-](assisted|written|coded|authored)\b",
        r"(auto|automatically)[\s\-]generated (by|with) (ai|llm|gpt)",
        r"generated by (an |a )?(ai|llm|language model)",
        r"\bmachine[\s\-]generated code\b",
        r"ai pair program",
    ],
}


def detect_attribution(commit_message: str) -> tuple:
    """Return (is_llm, tool, signal_strength, signal_type)."""
    msg = commit_message.lower()
    for tool, patterns in STRONG_PATTERNS.items():
        for p in patterns:
            if re.search(p, msg, re.IGNORECASE):
                return True, tool, "strong", "coauthor"
    for tool, patterns in MEDIUM_PATTERNS.items():
        for p in patterns:
            if re.search(p, msg, re.IGNORECASE):
                return True, tool, "medium", "commit_message"
    return False, None, None, None


def selftest() -> None:
    cases = [
        "Fix buffer overflow\n\nCo-authored-by: GitHub Copilot",
        "Add authentication handler - generated with ChatGPT",
        "Refactor memory management using cursor ai",
        "Update README",  # should NOT match
    ]
    for m in cases:
        is_llm, tool, strength, _ = detect_attribution(m)
        print(f"  {m[:50]!r} -> {f'{tool} [{strength}]' if is_llm else 'human'}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        selftest()
        return

    n_total = n_ai = 0
    by_tool, by_strength = Counter(), Counter()
    with open(RAW_COMMITS, encoding="utf-8") as fin, \
         open(AI_COMMITS, "w", encoding="utf-8") as fout:
        for line in fin:
            rec = json.loads(line)
            n_total += 1
            is_llm, tool, strength, sig_type = detect_attribution(rec["commit_message"])
            if not is_llm:
                continue
            rec.update(ai_tool=tool, signal_strength=strength, signal_type=sig_type)
            fout.write(json.dumps(rec, ensure_ascii=False) + "\n")
            n_ai += 1
            by_tool[tool] += 1
            by_strength[strength] += 1

    print(f"Commits scanned:    {n_total:,}")
    print(f"AI-attributed:      {n_ai:,}")
    print(f"By tool:            {dict(by_tool)}")
    print(f"By signal strength: {dict(by_strength)}")
    print(f"Output: {AI_COMMITS}")


if __name__ == "__main__":
    main()
